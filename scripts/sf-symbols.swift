import AppKit

//
// Writes src/lib/sf-symbols.ts: the SF Symbols the window draws, as SVG path data.
//
//   npm run symbols
//
// After Timekeeper's script of the same name, trimmed to window icons. macOS keeps a symbol's
// vector layers in CoreGlyphs, and the only way to that geometry without the SF Symbols app is
// CoreUI's private `vectorGlyph`. That is acceptable here and nowhere else: this runs on a
// developer's Mac, its output is committed, and nothing private ships. If a macOS update breaks
// it, the committed file keeps working.
//
// Apple's licence allows SF Symbols in the interface of software for Apple platforms, never in an
// app icon or logo: nothing here may end up in the plugin's or an action's icon.
//

/// The window's icons, each on a viewBox of its own ink, sized by CSS.
let icons = ["newspaper", "globe", "sidebar.right"]

/// Symbols whose layers marked as erasers are ink. On macOS 27 `globe` comes as its ring plus its
/// meridians as two "eraser" layers; subtracting them leaves stubs on a bare ring, and leaving
/// them out a plain ring. Look at a symbol drawn here before adding it.
let erasersAreInk: Set<String> = ["globe"]

/// Beside 12–13px window text, matching the stroke of the Lucide icons around them.
let iconWeight = NSFont.Weight.medium

struct Layer { let role: String; let path: CGPath }

func layers(of name: String, weight: NSFont.Weight) -> [Layer] {
    guard let base = NSImage(systemSymbolName: name, accessibilityDescription: nil),
          let image = base.withSymbolConfiguration(.init(pointSize: 100, weight: weight)),
          let rep = image.representations.first,
          let glyph = rep.perform(NSSelectorFromString("vectorGlyph"))?.takeUnretainedValue() as? NSObject,
          let found = glyph.value(forKey: "multicolorLayers") as? [NSObject]
    else {
        FileHandle.standardError.write("no vector glyph for \(name)\n".data(using: .utf8)!)
        exit(1)
    }
    return found.map { layer -> Layer in
        let layerName = layer.value(forKey: "name") as! String
        let path = glyph.perform(NSSelectorFromString("pathForLayerNamed:"), with: layerName)!
            .takeUnretainedValue() as! NSObject
        let cg = path.perform(NSSelectorFromString("path"))!.takeUnretainedValue() as! CGPath
        let colour = layer.value(forKey: "fillColorName") as? String ?? ""
        let eraser = layer.value(forKey: "isEraserLayer") as? Bool ?? false
        let role = eraser ? "eraser"
            : colour == "systemYellowColor" ? "yellow"
            : colour == "systemCyanColor" || colour == "systemBlueColor" ? "blue"
            : "ink"
        return Layer(role: role, path: cg)
    }
    .reduce(into: [Layer]()) { painted, layer in
        // An eraser cuts through everything painted before it, and is not ink itself.
        if layer.role == "eraser" && erasersAreInk.contains(name) {
            painted.append(Layer(role: "ink", path: layer.path))
        } else if layer.role == "eraser" {
            painted = painted.map { Layer(role: $0.role, path: $0.path.subtracting(layer.path)) }
        } else {
            painted.append(layer)
        }
    }
}

func bounds(_ layers: [Layer]) -> CGRect {
    layers.map { $0.path.boundingBoxOfPath }.reduce(CGRect.null) { $0.union($1) }
}

func svg(_ path: CGPath, _ t: CGAffineTransform) -> String {
    func n(_ v: CGFloat) -> String {
        var s = String(format: "%.2f", Double(v))
        while s.contains(".") && (s.hasSuffix("0") || s.hasSuffix(".")) { s.removeLast() }
        return s == "-0" ? "0" : s
    }
    func p(_ pt: CGPoint) -> String { let q = pt.applying(t); return "\(n(q.x)) \(n(q.y))" }
    var d = ""
    path.applyWithBlock { el in
        let e = el.pointee
        switch e.type {
        case .moveToPoint: d += "M\(p(e.points[0]))"
        case .addLineToPoint: d += "L\(p(e.points[0]))"
        case .addQuadCurveToPoint: d += "Q\(p(e.points[0])) \(p(e.points[1]))"
        case .addCurveToPoint: d += "C\(p(e.points[0])) \(p(e.points[1])) \(p(e.points[2]))"
        case .closeSubpath: d += "Z"
        @unknown default: break
        }
    }
    return d
}

var out = """
// Generated by scripts/sf-symbols.swift on macOS \(ProcessInfo.processInfo.operatingSystemVersionString).
// Do not edit: change the script and run `npm run symbols`.
//
// SF Symbols, Apple. Licensed for the interface of software on Apple platforms; never an app icon
// or logo, so none of this may go into the plugin's or an action's icon.

/** Window icons, one colour, on a viewBox fitted to their ink so CSS sets the size. */
export const SYMBOL_ICONS = {

"""
for name in icons {
    let ls = layers(of: name, weight: iconWeight)
    let b = bounds(ls)
    // On a 24-unit-tall box, like the Lucide icons beside them, so a height means the same.
    let k = 24 / b.height
    let t = CGAffineTransform(translationX: -b.minX * k, y: -b.minY * k).scaledBy(x: k, y: k)
    let d = ls.map { svg($0.path, t) }.joined()
    let w = String(format: "%.2f", Double(b.width * k))
    out += "\t\"\(name)\": { viewBox: \"0 0 \(w) 24\", d: \"\(d)\" },\n"
}
out += "} as const;\n"

try! out.write(toFile: CommandLine.arguments.count > 1 ? CommandLine.arguments[1] : "src/lib/sf-symbols.ts",
               atomically: true, encoding: .utf8)
